#!/usr/bin/env node
// Generates docs/architecture/asyncapi.yaml from the event registry
// (libs/events/src/registry.ts): one AsyncAPI message per event type,
// one channel per stream. Each message's payload is the whole CloudEvents
// envelope that goes on the wire (id, type, source, time, subject, silo,
// principal, correlation, data), with `data` pointing at that event's own
// zod schema, all built with zod's `z.toJSONSchema`. Each message's example
// is a full valid event, on the subject its stream requires.
//
// Run `npm run gen:asyncapi` after changing the registry, and commit the
// result. `npm run check:asyncapi` (wired into CI) regenerates the
// document in memory and fails the build if it doesn't match the
// committed file, the same way a lockfile check would.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { stringify } from 'yaml';
import { eventEnvelopeSchema } from '../libs/events/src/envelope.ts';
import { eventRegistry } from '../libs/events/src/registry.ts';
import { expectedSubject } from '../libs/events/src/subject.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const outputPath = path.join(repoRoot, 'docs/architecture/asyncapi.yaml');

const HEADER = [
  '# Generated by `npm run gen:asyncapi` from libs/events/src/registry.ts.',
  "# Do not edit by hand: `npm run check:asyncapi` (in CI) fails if this file",
  "# doesn't match what the registry would generate. See",
  '# docs/architecture/events.md for the prose version of this catalogue.',
  '',
].join('\n');

// The fixed envelope fields used in every generated example event.
const EXAMPLE_SILO = 'acme';
const EXAMPLE_ENVELOPE = {
  id: 'evt_1',
  source: 'opencrane-server',
  time: '2026-10-01T09:00:00.000Z',
  silo: EXAMPLE_SILO,
};

/**
 * AsyncAPI schemas are JSON Schema draft-07. Zod adds a "$schema" key to
 * each document, which does not belong inside a component, so drop it.
 *
 * @param {import('zod').ZodType} schema
 * @returns {Record<string, unknown>}
 */
function toJsonSchema(schema) {
  const { $schema: _dropped, ...rest } = z.toJSONSchema(schema, { target: 'draft-7' });
  return rest;
}

/**
 * "member.joined" -> "memberJoined": AsyncAPI component names have to be
 * plain identifiers, but event types are dotted and underscored.
 *
 * @param {string} eventType
 * @returns {string}
 */
export function toComponentName(eventType) {
  return eventType
    .split(/[._]/)
    .filter((word) => word.length > 0)
    .map((word, index) => (index === 0 ? word : word.charAt(0).toUpperCase() + word.slice(1)))
    .join('');
}

/**
 * The human-readable subject pattern for one event's stream binding (see
 * libs/events/src/subject.ts), e.g. `member-<memberId>` or, for the one
 * composite stream, `connection-<userId>-<serverId>-<profile>`.
 *
 * @param {import('../libs/events/src/registry.ts').EventDefinition} entry
 * @returns {string}
 */
export function subjectPattern(entry) {
  if (entry.subjectFields === 'silo') {
    return `${entry.stream}-<silo>`;
  }
  return `${entry.stream}-${entry.subjectFields.map((field) => `<${field}>`).join('-')}`;
}

/**
 * Builds the AsyncAPI document as a plain object, ready to serialise.
 *
 * @returns {Record<string, unknown>}
 */
export function buildDocument() {
  const streamTypes = [...new Set(eventRegistry.map((entry) => entry.stream))].sort();

  /** @type {Record<string, unknown>} */
  const messages = {};
  /** @type {Record<string, unknown>} */
  const schemas = { EventEnvelope: toJsonSchema(eventEnvelopeSchema(z.unknown())) };

  for (const entry of eventRegistry) {
    const name = toComponentName(entry.type);
    schemas[`${name}Data`] = toJsonSchema(entry.dataSchema);
    messages[name] = {
      name: entry.type,
      title: entry.type,
      summary: entry.description,
      payload: {
        allOf: [
          { $ref: '#/components/schemas/EventEnvelope' },
          {
            type: 'object',
            properties: {
              type: { const: entry.type },
              data: { $ref: `#/components/schemas/${name}Data` },
            },
          },
        ],
      },
      'x-stream-subject': subjectPattern(entry),
      examples: [
        {
          name: 'default',
          payload: {
            ...EXAMPLE_ENVELOPE,
            type: entry.type,
            subject: expectedSubject(entry, entry.example, EXAMPLE_SILO),
            data: entry.example,
          },
        },
      ],
    };
  }

  /** @type {Record<string, unknown>} */
  const channels = {};
  for (const stream of streamTypes) {
    const streamEntries = eventRegistry.filter((entry) => entry.stream === stream);
    channels[stream] = {
      address: `ev.${stream}.>`,
      messages: Object.fromEntries(
        streamEntries.map((entry) => {
          const name = toComponentName(entry.type);
          return [name, { $ref: `#/components/messages/${name}` }];
        }),
      ),
    };
  }

  return {
    asyncapi: '3.0.0',
    info: {
      title: 'OpenCrane 2 event catalogue',
      version: '1.0.0',
      description:
        'Every event type in libs/events/src/registry.ts, generated from its zod schema. See docs/architecture/events.md for which projection or reaction reads each one.',
    },
    channels,
    components: { messages, schemas },
  };
}

/** @returns {string} */
export function renderDocument() {
  // YAML 1.1 mode quotes strings an older YAML reader would turn into dates
  // or booleans (an example `time`, or the word "yes"), so every reader
  // sees the same document.
  return HEADER + stringify(buildDocument(), { lineWidth: 0, version: '1.1' });
}

async function main() {
  const checkOnly = process.argv.includes('--check');
  const rendered = renderDocument();

  if (!checkOnly) {
    await writeFile(outputPath, rendered, 'utf8');
    console.log(`gen:asyncapi — wrote ${outputPath}`);
    return;
  }

  let existing;
  try {
    existing = await readFile(outputPath, 'utf8');
  } catch (error) {
    if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') {
      console.error(`check:asyncapi — FAILED: ${outputPath} does not exist. Run \`npm run gen:asyncapi\`.`);
      process.exitCode = 1;
      return;
    }
    throw error;
  }

  if (existing !== rendered) {
    console.error(
      'check:asyncapi — FAILED: docs/architecture/asyncapi.yaml is out of date. Run `npm run gen:asyncapi` and commit the result.',
    );
    process.exitCode = 1;
    return;
  }

  console.log('check:asyncapi — OK: docs/architecture/asyncapi.yaml matches the registry.');
}

// Only run when this file is executed directly, not when a test imports
// it for its exported building blocks.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
